public class literalsConcepts {
    public static void main(String[] args) {
        int a = 10;
        float b = 5.6f;
        char c = 'B';
        String name = "Nancy";
        boolean d = true;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(name);
        System.out.println(d);
    }
}
